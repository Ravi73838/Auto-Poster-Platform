import { ASSIGNMENT_STATUS, type AssignmentStatus } from '@ap/shared-constants';
import {
  createStateMachine,
  type StateMachine,
} from '../../shared/state-machine/index.js';

export const ASSIGNMENT_TRANSITIONS: Record<
  AssignmentStatus,
  readonly AssignmentStatus[]
> = {
  [ASSIGNMENT_STATUS.RESERVED]: [
    ASSIGNMENT_STATUS.INSTALLING,
    ASSIGNMENT_STATUS.RELEASED,
    ASSIGNMENT_STATUS.RESERVATION_EXPIRED,
    ASSIGNMENT_STATUS.TERMINATED,
  ],
  [ASSIGNMENT_STATUS.INSTALLING]: [
    ASSIGNMENT_STATUS.INSTALL_SUBMITTED,
    ASSIGNMENT_STATUS.RELEASED,
    ASSIGNMENT_STATUS.RESERVATION_EXPIRED,
    ASSIGNMENT_STATUS.TERMINATED,
  ],
  [ASSIGNMENT_STATUS.INSTALL_SUBMITTED]: [
    ASSIGNMENT_STATUS.INSTALL_APPROVED,
    ASSIGNMENT_STATUS.INSTALL_REJECTED,
    ASSIGNMENT_STATUS.TERMINATED,
  ],
  [ASSIGNMENT_STATUS.INSTALL_REJECTED]: [
    ASSIGNMENT_STATUS.INSTALLING,
    ASSIGNMENT_STATUS.INSTALL_SUBMITTED,
    ASSIGNMENT_STATUS.INSTALL_APPROVED,
    ASSIGNMENT_STATUS.RELEASED,
    ASSIGNMENT_STATUS.TERMINATED,
  ],
  [ASSIGNMENT_STATUS.INSTALL_APPROVED]: [
    ASSIGNMENT_STATUS.RUNNING,
    ASSIGNMENT_STATUS.TERMINATED,
  ],
  [ASSIGNMENT_STATUS.RUNNING]: [
    ASSIGNMENT_STATUS.COMPLETED,
    ASSIGNMENT_STATUS.TERMINATED,
  ],
  [ASSIGNMENT_STATUS.COMPLETED]: [
    ASSIGNMENT_STATUS.PAID,
    ASSIGNMENT_STATUS.TERMINATED,
  ],
  [ASSIGNMENT_STATUS.PAID]: [],
  [ASSIGNMENT_STATUS.TERMINATED]: [ASSIGNMENT_STATUS.RUNNING],
  [ASSIGNMENT_STATUS.RESERVATION_EXPIRED]: [],
  [ASSIGNMENT_STATUS.RELEASED]: [],
};

export const assignmentStateMachine: StateMachine<AssignmentStatus> =
  createStateMachine({
    transitions: ASSIGNMENT_TRANSITIONS,
  });
